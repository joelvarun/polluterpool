"""Generate a real pytest suite with planted order dependencies.

Every polluter mutates process state through a keyed channel (a module level
dict, an environment variable, ``sys.path``, or a lazily built singleton) and
every victim asserts that its own channels are untouched. Keying each channel
to one polluter keeps the ground truth exact: a victim fails if and only if at
least one of its own polluters ran earlier in the same process.
"""

from __future__ import annotations

import argparse
import json
import os
import random
from typing import Dict, List, Tuple

SHARED = '''"""Mutable process state shared by the generated tests."""

STATE = {}
_REGISTRY = None


def registry():
    global _REGISTRY
    if _REGISTRY is None:
        _REGISTRY = set()
    return _REGISTRY
'''

HEADER = '''"""Generated by examples/gen_suite.py. Do not edit by hand."""

import os
import sys

import shared_state

'''

DIRTY = {
    "state": '    shared_state.STATE["{key}"] = 1\n',
    "env": '    os.environ["PPENV_{key}"] = "1"\n',
    "path": '    sys.path.insert(0, "/polluterpool/{key}")\n',
    "registry": '    shared_state.registry().add("{key}")\n',
}

CHECK = {
    "state": '    assert "{key}" not in shared_state.STATE\n',
    "env": '    assert "PPENV_{key}" not in os.environ\n',
    "path": '    assert "/polluterpool/{key}" not in sys.path\n',
    "registry": '    assert "{key}" not in shared_state.registry()\n',
}

CHANNELS = list(DIRTY)


def build(n_tests: int, n_victims: int, max_polluters: int, per_module: int, seed: int):
    rng = random.Random(seed)
    names = [f"test_t{i:04d}" for i in range(n_tests)]
    modules = [
        (f"test_seg{i // per_module:02d}.py", names[i : i + per_module])
        for i in range(0, n_tests, per_module)
    ]
    order: List[str] = []
    for filename, members in modules:
        order.extend(f"{filename}::{name}" for name in members)
    position = {nodeid: i for i, nodeid in enumerate(order)}

    victims = sorted(
        rng.sample(order[n_tests // 4 :], n_victims), key=position.__getitem__
    )
    truth: Dict[str, List[str]] = {}
    dirty: Dict[str, List[Tuple[str, str]]] = {}
    checks: Dict[str, List[Tuple[str, str]]] = {}
    key_counter = 0
    for victim in victims:
        candidates = order[: position[victim]]
        count = min(rng.randint(1, max_polluters), len(candidates))
        chosen = sorted(rng.sample(candidates, count), key=position.__getitem__)
        truth[victim] = chosen
        for polluter in chosen:
            channel = CHANNELS[key_counter % len(CHANNELS)]
            key = f"k{key_counter:04d}"
            key_counter += 1
            dirty.setdefault(polluter, []).append((channel, key))
            checks.setdefault(victim, []).append((channel, key))
    return modules, order, victims, truth, dirty, checks


def render(modules, dirty, checks) -> Dict[str, str]:
    """A test dirties before it asserts.

    A victim that is itself a polluter must leave its mark whether or not its
    own assertions hold, otherwise one test failing would silently change what
    the tests after it see.
    """
    files: Dict[str, str] = {}
    for filename, members in modules:
        chunks = [HEADER]
        for index, name in enumerate(members):
            nodeid = f"{filename}::{name}"
            lines = [f"def {name}():\n"]
            for channel, key in dirty.get(nodeid, []):
                lines.append(DIRTY[channel].format(key=key))
            for channel, key in checks.get(nodeid, []):
                lines.append(CHECK[channel].format(key=key))
            lines.append(f"    assert ({index} * 7 + 3) % 7 == {(index * 7 + 3) % 7}\n")
            chunks.append("".join(lines))
        files[filename] = "\n\n".join(chunks) + "\n"
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tests", type=int, default=100)
    parser.add_argument("--victims", type=int, default=6)
    parser.add_argument("--max-polluters", type=int, default=3)
    parser.add_argument("--per-module", type=int, default=10)
    parser.add_argument("--seed", type=int, default=20251002)
    parser.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "demo_suite"))
    args = parser.parse_args()

    modules, order, victims, truth, dirty, checks = build(
        args.tests, args.victims, args.max_polluters, args.per_module, args.seed
    )
    os.makedirs(args.out, exist_ok=True)
    for stale in os.listdir(args.out):
        if stale.startswith("test_seg") or stale in {"shared_state.py", "manifest.json"}:
            os.remove(os.path.join(args.out, stale))
    with open(os.path.join(args.out, "shared_state.py"), "w", encoding="utf-8") as fh:
        fh.write(SHARED)
    for filename, text in render(modules, dirty, checks).items():
        with open(os.path.join(args.out, filename), "w", encoding="utf-8") as fh:
            fh.write(text)
    manifest = {
        "order": order,
        "victims": victims,
        "ground_truth": {v: truth[v] for v in victims},
        "seed": args.seed,
    }
    with open(os.path.join(args.out, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    pairs = sum(len(v) for v in truth.values())
    print(f"{len(order)} tests, {len(victims)} victims, {pairs} polluter-victim pairs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
